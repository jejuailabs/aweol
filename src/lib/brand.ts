/**
 * 이 서비스의 이름 — **한 곳에서만 정한다.**
 *
 * 처음엔 '애월초 학급 전시실' 이었다. 한 학교의 한 학급을 위해 시작했으니
 * 맞는 이름이었지만, 지금은 여러 학교가 들어오고 개인 전시관까지 선다.
 * 그런데 이름이 화면마다 따로 박혀 있어서, 퍼가기로 보낸 링크에는
 * 여전히 남의 학교 이름이 찍혀 나갔다.
 *
 * **이름은 반드시 여기서 가져다 쓴다.** 글자로 다시 적는 순간
 * 반드시 한쪽이 낡는다 — 지금까지가 그랬다.
 */
export const BRAND = '우리들의 온라인 전시실';

/** 한 줄 소개 — 퍼가기·검색 결과에 함께 나간다 */
export const BRAND_TAGLINE =
  '우리 동네를 걸어 다니며 친구들의 작품을 만나는 3D 전시실';

/**
 * 퍼가기에 붙이는 제목.
 *
 * **무엇을 퍼가는지가 앞에 온다.** '우리들의 온라인 전시실' 만 보내면
 * 받은 사람은 무엇을 보라는 건지 모른다. 뒤에 서비스 이름을 달아
 * 어디서 온 링크인지 알게 한다.
 */
export const shareTitle = (what?: string) =>
  what && what.trim() ? `${what.trim()} · ${BRAND}` : BRAND;
